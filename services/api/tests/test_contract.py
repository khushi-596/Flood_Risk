"""Contract and schema conformance test suite.

Verifies:
1. Complete OpenAPI 3.1 schema structure generated by FastAPI (/openapi.json)
2. Schema consistency across all operations, parameters, request bodies, and responses
3. Schemathesis property-based contract testing across all endpoints (with importorskip)
"""

import pytest
from fastapi.testclient import TestClient

from app.main import app

client = TestClient(app)


def test_openapi_schema_structure():
    """Verify OpenAPI 3.x schema generation and metadata."""
    res = client.get("/openapi.json")
    assert res.status_code == 200
    schema = res.json()

    assert "openapi" in schema
    assert schema["info"]["title"] == "Flood-Aware Route & Road Risk API"
    assert "paths" in schema

    paths = schema["paths"]
    # Check key endpoint paths exist
    assert "/v1/health" in paths
    assert "/v1/segments" in paths
    assert "/v1/rain" in paths
    assert "/v1/routes/compare" in paths
    assert "/v1/travel-advice" in paths
    assert "/v1/reports" in paths
    assert "/v1/municipal/login" in paths
    assert "/v1/municipal/work-orders" in paths

    # Verify that each path defines at least one valid HTTP method with 2xx response
    for path, methods in paths.items():
        for method, spec in methods.items():
            if method in {"get", "post", "put", "patch", "delete"}:
                assert "responses" in spec, f"Endpoint {method.upper()} {path} lacks responses"
                # Check for either a 200, 201, or default response
                has_success = any(code.startswith("2") for code in spec["responses"].keys())
                assert has_success, f"Endpoint {method.upper()} {path} has no 2xx response documented"


def test_openapi_tags_and_descriptions():
    """Ensure all routes are documented with meaningful tags and summaries."""
    schema = client.get("/openapi.json").json()
    for path, methods in schema["paths"].items():
        for method, spec in methods.items():
            if method in {"get", "post", "put", "patch", "delete"}:
                assert "tags" in spec and len(spec["tags"]) > 0, f"{method.upper()} {path} missing tags"


# ---------------------------------------------------------------------------
# Schemathesis Property-Based Contract Testing
# ---------------------------------------------------------------------------

schemathesis = pytest.importorskip("schemathesis", reason="schemathesis is optional")


def test_schemathesis_contract_fuzzing():
    """Verify Schemathesis case generation and contract compliance on public routes."""
    schema = schemathesis.openapi.from_dict(app.openapi())
    for path in ("/v1/health", "/v1/rain", "/v1/segments"):
        operation = schema.find_operation_by_path(path=path, method="get")
        assert operation is not None
        case = operation.as_strategy().example()
        res = client.get(case.formatted_path)
        assert res.status_code < 500
        assert res.status_code == 200
